# =============================================================================
# CLEAN DATASET INDEXING
# =============================================================================

def index_clean_requirements(
    requirements: list[dict[str, Any]]
) -> tuple[
    dict[str, dict[str, Any]],
    Counter,
]:
    """
    Builds an ID -> requirement index and counts duplicate IDs.
    """

    indexed = {}
    id_counts = Counter()

    for requirement in requirements:
        requirement_id = requirement.get("id")

        if not isinstance(requirement_id, str):
            continue

        requirement_id = normalize_whitespace(requirement_id)

        id_counts[requirement_id] += 1

        # Preserve the first occurrence for auditing.
        if requirement_id not in indexed:
            indexed[requirement_id] = requirement

    return indexed, id_counts


# =============================================================================
# DEBUG CANDIDATE INDEXING
# =============================================================================

def collect_debug_candidates(
    debug_data: dict[str, Any]
) -> dict[str, list[dict[str, Any]]]:
    """
    Collects every candidate occurrence of each requirement ID across blocks.

    Each occurrence preserves:
        - block_id
        - central_pages
        - context_pages
        - candidate fields
    """

    candidates_by_id = defaultdict(list)

    blocks = debug_data.get("blocks", [])

    if not isinstance(blocks, list):
        return candidates_by_id

    for block in blocks:
        if not isinstance(block, dict):
            continue

        block_id = block.get("block_id")
        central_pages = block.get("central_pages", [])
        context_pages = block.get("context_pages", [])

        requirements = block.get("requirements", [])

        if not isinstance(requirements, list):
            continue

        for requirement in requirements:
            if not isinstance(requirement, dict):
                continue

            requirement_id = requirement.get("id")

            if not isinstance(requirement_id, str):
                continue

            requirement_id = normalize_whitespace(requirement_id)

            occurrence = {
                "block_id": block_id,
                "central_pages": central_pages,
                "context_pages": context_pages,
                "id": requirement_id,
                "type": requirement.get("type"),
                "title": requirement.get("title"),
                "text": requirement.get("text"),
            }

            candidates_by_id[requirement_id].append(occurrence)

    return candidates_by_id


# =============================================================================
# CONTAMINATION AUDIT
# =============================================================================

def find_contamination(text: str) -> list[str]:
    """
    Returns all contamination categories detected in the text.
    """

    findings = []

    if not isinstance(text, str):
        return findings

    for name, pattern in CONTAMINATION_PATTERNS.items():
        if pattern.search(text):
            findings.append(name)

    return findings


# =============================================================================
# NORMATIVE TEXT HEURISTICS
# =============================================================================

def assess_normative_start(text: str) -> dict[str, Any]:
    """
    Performs a conservative heuristic check.

    IEC normative requirements generally contain 'shall'. We do not require
    that the text literally starts with 'The control system shall', because
    valid requirements may begin with conditional or contextual clauses.

    Examples:
        "If cryptography is required, the control system shall ..."
        "For software process and device users, ..."
        "On all interfaces, the control system shall ..."
    """

    normalized = normalize_whitespace(text)

    if not normalized:
        return {
            "status": "fail",
            "reason": "empty_text",
        }

    if " shall " in f" {normalized.lower()} ":
        return {
            "status": "pass",
            "reason": "contains_shall",
        }

    return {
        "status": "warning",
        "reason": "no_shall_detected",
    }


# =============================================================================
# DEBUG CONSISTENCY
# =============================================================================

def audit_debug_candidates(
    requirement_id: str,
    final_requirement: dict[str, Any],
    occurrences: list[dict[str, Any]],
) -> dict[str, Any]:
    """
    Audits consistency between:
        - all block-level candidates
        - final consolidated requirement
    """

    final_title = final_requirement.get("title", "")
    final_text = final_requirement.get("text", "")

    result = {
        "candidate_occurrences": len(occurrences),
        "unique_text_variants": 0,
        "unique_title_variants": 0,
        "min_text_similarity_to_final": None,
        "max_text_similarity_to_final": None,
        "average_text_similarity_to_final": None,
        "prefix_variants_detected": False,
        "exact_final_match_found": False,
        "title_variants": [],
        "text_variants": [],
        "issues": [],
    }

    if not occurrences:
        result["issues"].append("not_found_in_debug_blocks")
        return result

    normalized_texts = defaultdict(list)
    normalized_titles = defaultdict(list)

    similarities = []
    prefix_detected = False
    exact_match = False

    for occurrence in occurrences:

        title = occurrence.get("title", "")
        text = occurrence.get("text", "")

        title_key = normalize_for_comparison(title)
        text_key = normalize_for_comparison(text)

        normalized_titles[title_key].append(occurrence)
        normalized_texts[text_key].append(occurrence)

        similarity = text_similarity(final_text, text)
        similarities.append(similarity)

        if similarity >= 0.999:
            exact_match = True

        if is_prefix_variant(final_text, text) and similarity < 0.999:
            prefix_detected = True

    result["unique_text_variants"] = len(normalized_texts)
    result["unique_title_variants"] = len(normalized_titles)

    result["exact_final_match_found"] = exact_match
    result["prefix_variants_detected"] = prefix_detected

    if similarities:
        result["min_text_similarity_to_final"] = round(min(similarities), 4)
        result["max_text_similarity_to_final"] = round(max(similarities), 4)
        result["average_text_similarity_to_final"] = round(
            sum(similarities) / len(similarities),
            4,
        )

    # Record variants only when there is more than one distinct version.
    if len(normalized_titles) > 1:
        result["title_variants"] = [
            {
                "title": occurrences_for_variant[0].get("title"),
                "blocks": [
                    occurrence.get("block_id")
                    for occurrence in occurrences_for_variant
                ],
            }
            for occurrences_for_variant in normalized_titles.values()
        ]

        result["issues"].append("multiple_title_variants")

    if len(normalized_texts) > 1:
        result["text_variants"] = [
            {
                "text": occurrences_for_variant[0].get("text"),
                "blocks": [
                    occurrence.get("block_id")
                    for occurrence in occurrences_for_variant
                ],
            }
            for occurrences_for_variant in normalized_texts.values()
        ]

        result["issues"].append("multiple_text_variants")

    if not exact_match:
        result["issues"].append(
            "final_text_not_exactly_present_in_debug_candidates"
        )

    if prefix_detected:
        result["issues"].append("prefix_or_truncation_variant_detected")

    # Strong inconsistency:
    # the final text is substantially different from at least one candidate.
    if (
        result["min_text_similarity_to_final"] is not None
        and result["min_text_similarity_to_final"] < 0.70
    ):
        result["issues"].append("low_similarity_candidate_variant")

    return result


# =============================================================================
# DUPLICATE CONTENT DETECTION
# =============================================================================

def find_duplicate_content(
    requirements: list[dict[str, Any]]
) -> dict[str, list[str]]:
    """
    Detects exact normalized duplicate texts.

    Duplicate text is not automatically an error because some IEC requirements
    can legitimately have similar wording. Therefore this is reported as an
    observation rather than a structural failure.
    """

    by_text = defaultdict(list)

    for requirement in requirements:
        requirement_id = requirement.get("id")
        text = requirement.get("text", "")

        if not isinstance(requirement_id, str):
            continue

        normalized = normalize_for_comparison(text)

        if normalized:
            by_text[normalized].append(requirement_id)

    duplicates = {}

    for text, ids in by_text.items():
        if len(ids) > 1:
            duplicates[text] = ids

    return duplicates


# =============================================================================
# PER-ENTRY AUDIT
# =============================================================================

def audit_requirement(
    requirement: dict[str, Any],
    all_clean_ids: set[str],
    debug_candidates_by_id: dict[str, list[dict[str, Any]]],
    consolidated_debug: dict[str, Any],
) -> dict[str, Any]:
    """
    Performs the complete audit of one requirement.
    """

    requirement_id = normalize_whitespace(
        requirement.get("id", "")
    )

    requirement_type = requirement.get("type")
    title = requirement.get("title")
    text = requirement.get("text")
    parent_sr = requirement.get("parent_sr")
    foundational_requirement = requirement.get(
        "foundational_requirement"
    )

    issues = []
    warnings = []

    checks = {
        "valid_id": False,
        "valid_type": False,
        "title_present": False,
        "text_present": False,
        "parent_valid": False,
        "fr_consistent": False,
        "normative_text": False,
        "contamination_free": False,
        "debug_consistency": False,
    }

    # -------------------------------------------------------------------------
    # ID
    # -------------------------------------------------------------------------

    parsed = parse_requirement_id(requirement_id)

    if parsed["valid"]:
        checks["valid_id"] = True
    else:
        issues.append("invalid_requirement_id")

    # -------------------------------------------------------------------------
    # Type
    # -------------------------------------------------------------------------

    if requirement_type in {"SR", "RE"}:
        checks["valid_type"] = True
    else:
        issues.append("invalid_or_missing_type")

    # Ensure ID and declared type agree.
    if parsed["valid"] and requirement_type:
        if parsed["type"] != requirement_type:
            issues.append("id_type_mismatch")

    # -------------------------------------------------------------------------
    # Title
    # -------------------------------------------------------------------------

    if isinstance(title, str) and normalize_whitespace(title):
        checks["title_present"] = True
    else:
        issues.append("missing_title")

    # -------------------------------------------------------------------------
    # Text
    # -------------------------------------------------------------------------

    if isinstance(text, str) and normalize_whitespace(text):
        checks["text_present"] = True
    else:
        issues.append("missing_text")

    # -------------------------------------------------------------------------
    # Parent
    # -------------------------------------------------------------------------

    expected_parent = parsed["parent_sr"] if parsed["valid"] else None

    if (
        isinstance(parent_sr, str)
        and expected_parent
        and normalize_whitespace(parent_sr) == expected_parent
    ):

        if requirement_type == "SR":
            checks["parent_valid"] = True

        elif requirement_type == "RE":

            if expected_parent in all_clean_ids:
                checks["parent_valid"] = True
            else:
                issues.append("missing_parent_sr")

    else:
        issues.append("invalid_parent_sr")

    # -------------------------------------------------------------------------
    # Foundational Requirement
    # -------------------------------------------------------------------------

    if parsed["valid"]:

        if foundational_requirement == parsed["fr"]:
            checks["fr_consistent"] = True
        else:
            issues.append("foundational_requirement_mismatch")

    # -------------------------------------------------------------------------
    # Normative text
    # -------------------------------------------------------------------------

    normative = assess_normative_start(text)

    if normative["status"] == "pass":
        checks["normative_text"] = True
    else:
        warnings.append(normative["reason"])

    # -------------------------------------------------------------------------
    # Contamination
    # -------------------------------------------------------------------------

    contamination = find_contamination(text)

    if not contamination:
        checks["contamination_free"] = True
    else:
        for finding in contamination:
            issues.append(f"possible_text_contamination:{finding}")

    # -------------------------------------------------------------------------
    # Suspiciously short text
    # -------------------------------------------------------------------------

    word_count = len(normalize_whitespace(text).split())

    if word_count < 5:
        warnings.append("suspiciously_short_text")

    # -------------------------------------------------------------------------
    # Debug consistency
    # -------------------------------------------------------------------------

    occurrences = debug_candidates_by_id.get(
        requirement_id,
        [],
    )

    debug_audit = audit_debug_candidates(
        requirement_id,
        requirement,
        occurrences,
    )

    if not debug_audit["issues"]:
        checks["debug_consistency"] = True
    else:
        warnings.extend(debug_audit["issues"])

    # -------------------------------------------------------------------------
    # Consolidated debug comparison
    # -------------------------------------------------------------------------

    consolidated = consolidated_debug.get(requirement_id)

    consolidated_comparison = {
        "found": consolidated is not None,
        "id_match": None,
        "title_similarity": None,
        "text_similarity": None,
    }

    if isinstance(consolidated, dict):

        consolidated_comparison["id_match"] = (
            normalize_whitespace(
                consolidated.get("id", "")
            )
            == requirement_id
        )

        consolidated_comparison["title_similarity"] = round(
            text_similarity(
                title or "",
                consolidated.get("title", ""),
            ),
            4,
        )

        consolidated_comparison["text_similarity"] = round(
            text_similarity(
                text or "",
                consolidated.get("text", ""),
            ),
            4,
        )

        if (
            consolidated_comparison["text_similarity"]
            is not None
            and consolidated_comparison["text_similarity"] < 0.999
        ):
            warnings.append(
                "clean_text_differs_from_debug_consolidation"
            )

    else:
        warnings.append("missing_debug_consolidation_entry")

    # -------------------------------------------------------------------------
    # Score
    # -------------------------------------------------------------------------

    score = sum(
        1
        for value in checks.values()
        if value
    )

    max_score = len(checks)

    # -------------------------------------------------------------------------
    # Status
    # -------------------------------------------------------------------------

    critical_issues = {
        "invalid_requirement_id",
        "invalid_or_missing_type",
        "id_type_mismatch",
        "missing_title",
        "missing_text",
        "invalid_parent_sr",
        "missing_parent_sr",
        "foundational_requirement_mismatch",
    }

    has_critical = any(
        issue.split(":")[0] in critical_issues
        for issue in issues
    )

    has_contamination = any(
        issue.startswith("possible_text_contamination")
        for issue in issues
    )

    if has_critical:
        status = "fail"

    elif has_contamination:
        status = "review"

    elif score == max_score and not warnings:
        status = "approved"

    else:
        status = "warning"

    return {
        "id": requirement_id,
        "type": requirement_type,
        "title": title,
        "foundational_requirement": foundational_requirement,
        "parent_sr": parent_sr,

        "word_count": word_count,

        "score": score,
        "max_score": max_score,

        "status": status,

        "checks": checks,

        "issues": sorted(set(issues)),
        "warnings": sorted(set(warnings)),

        "contamination": contamination,

        "normative_text_assessment": normative,

        "debug_candidate_audit": debug_audit,

        "debug_consolidated_comparison": (
            consolidated_comparison
        ),
    }


# =============================================================================
# DATASET-LEVEL AUDIT
# =============================================================================

def audit_dataset(
    clean_data: dict[str, Any],
    debug_data: dict[str, Any],
) -> dict[str, Any]:
    """
    Runs all dataset-level and requirement-level audits.
    """

    requirements = clean_data.get("requirements", [])

    if not isinstance(requirements, list):
        raise RuntimeError(
            "The clean dataset does not contain a valid "
            "'requirements' list."
        )

    clean_index, id_counts = index_clean_requirements(
        requirements
    )

    all_clean_ids = set(clean_index.keys())

    duplicate_ids = {
        requirement_id: count
        for requirement_id, count in id_counts.items()
        if count > 1
    }

    debug_candidates_by_id = collect_debug_candidates(
        debug_data
    )

    consolidated_debug = debug_data.get(
        "consolidated_requirements",
        {},
    )

    if not isinstance(consolidated_debug, dict):
        consolidated_debug = {}

    # -------------------------------------------------------------------------
    # SR and RE counts
    # -------------------------------------------------------------------------

    sr_entries = [
        requirement
        for requirement in requirements
        if requirement.get("type") == "SR"
    ]

    re_entries = [
        requirement
        for requirement in requirements
        if requirement.get("type") == "RE"
    ]

    actual_sr_ids = {
        normalize_whitespace(
            requirement.get("id", "")
        )
        for requirement in sr_entries
        if isinstance(requirement.get("id"), str)
    }

    missing_srs = sorted(
        EXPECTED_SR_IDS - actual_sr_ids
    )

    unexpected_srs = sorted(
        actual_sr_ids - EXPECTED_SR_IDS
    )

    # -------------------------------------------------------------------------
    # FR distribution
    # -------------------------------------------------------------------------

    fr_distribution = {}

    for fr in range(1, 8):

        fr_srs = [
            requirement
            for requirement in sr_entries
            if requirement.get("foundational_requirement") == fr
        ]

        fr_res = [
            requirement
            for requirement in re_entries
            if requirement.get("foundational_requirement") == fr
        ]

        expected_sr_count = EXPECTED_SRS[fr]

        fr_distribution[str(fr)] = {
            "sr_count": len(fr_srs),
            "re_count": len(fr_res),
            "expected_sr_count": expected_sr_count,
            "sr_count_matches_expected": (
                len(fr_srs) == expected_sr_count
            ),
        }

    # -------------------------------------------------------------------------
    # Exact duplicate content
    # -------------------------------------------------------------------------

    duplicate_texts = find_duplicate_content(
        requirements
    )

    duplicate_text_report = [
        {
            "ids": ids,
            "text": text,
        }
        for text, ids in duplicate_texts.items()
    ]

    # -------------------------------------------------------------------------
    # Per-entry audit
    # -------------------------------------------------------------------------

    entry_audits = []

    for requirement in requirements:

        audit = audit_requirement(
            requirement=requirement,
            all_clean_ids=all_clean_ids,
            debug_candidates_by_id=debug_candidates_by_id,
            consolidated_debug=consolidated_debug,
        )

        entry_audits.append(audit)

    # -------------------------------------------------------------------------
    # Status counts
    # -------------------------------------------------------------------------

    status_counts = Counter(
        audit["status"]
        for audit in entry_audits
    )

    # -------------------------------------------------------------------------
    # Missing debug entries
    # -------------------------------------------------------------------------

    missing_from_debug_blocks = [
        audit["id"]
        for audit in entry_audits
        if audit["debug_candidate_audit"]
        ["candidate_occurrences"] == 0
    ]

    # -------------------------------------------------------------------------
    # Missing debug consolidation
    # -------------------------------------------------------------------------

    missing_from_debug_consolidation = [
        audit["id"]
        for audit in entry_audits
        if not audit["debug_consolidated_comparison"]
        ["found"]
    ]

    # -------------------------------------------------------------------------
    # Dataset structural result
    # -------------------------------------------------------------------------

    structural_pass = (
        len(requirements) == EXPECTED_TOTAL_ENTRIES
        and len(sr_entries) == EXPECTED_TOTAL_SRS
        and len(re_entries) == EXPECTED_TOTAL_RES
        and not duplicate_ids
        and not missing_srs
        and not unexpected_srs
    )

    return {
        "metadata": {
            "audit_generated_at": (
                datetime.now(timezone.utc)
                .isoformat()
            ),
            "audit_script": "iec_audit.py",
            "clean_dataset": str(CLEAN_JSON_PATH),
            "debug_dataset": str(DEBUG_JSON_PATH),
            "expected_total_entries": EXPECTED_TOTAL_ENTRIES,
            "expected_total_srs": EXPECTED_TOTAL_SRS,
            "expected_total_res": EXPECTED_TOTAL_RES,
        },

        "dataset_summary": {
            "total_entries": len(requirements),
            "sr_count": len(sr_entries),
            "re_count": len(re_entries),

            "expected_total_entries": EXPECTED_TOTAL_ENTRIES,
            "expected_total_srs": EXPECTED_TOTAL_SRS,
            "expected_total_res": EXPECTED_TOTAL_RES,

            "structural_pass": structural_pass,

            "status_counts": dict(status_counts),

            "duplicate_id_count": len(duplicate_ids),

            "duplicate_text_group_count": len(
                duplicate_text_report
            ),

            "missing_sr_count": len(missing_srs),

            "unexpected_sr_count": len(
                unexpected_srs
            ),

            "missing_from_debug_blocks_count": len(
                missing_from_debug_blocks
            ),

            "missing_from_debug_consolidation_count": len(
                missing_from_debug_consolidation
            ),
        },

        "sr_coverage": {
            "expected_ids": sorted(EXPECTED_SR_IDS),
            "actual_ids": sorted(actual_sr_ids),
            "missing_ids": missing_srs,
            "unexpected_ids": unexpected_srs,
        },

        "foundational_requirement_distribution":
            fr_distribution,

        "duplicate_ids": duplicate_ids,

        "duplicate_texts": duplicate_text_report,

        "debug_coverage": {
            "missing_from_debug_blocks":
                missing_from_debug_blocks,

            "missing_from_debug_consolidation":
                missing_from_debug_consolidation,
        },

        "entries": entry_audits,
    }


