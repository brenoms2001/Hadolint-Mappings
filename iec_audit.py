def load_json(path: Path) -> Any:
    """
    Loads JSON with explicit error messages.
    """
    if not path.exists():
        raise FileNotFoundError(
            f"Required file not found:\n   {path}"
        )

    try:
        with path.open("r", encoding="utf-8") as file:
            return json.load(file)

    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"Invalid JSON in:\n   {path}\n\n"
            f"JSON error:\n   {exc}"
        ) from exc


# =============================================================================
# IEC ID HELPERS
# =============================================================================

def parse_requirement_id(requirement_id: str) -> dict[str, Any]:
    """
    Parses an IEC requirement ID.

    Examples:
        SR 1.1
        SR 1.1 RE 2
    """

    result = {
        "valid": False,
        "type": None,
        "fr": None,
        "sr_number": None,
        "re_number": None,
        "parent_sr": None,
    }

    if not isinstance(requirement_id, str):
        return result

    requirement_id = normalize_whitespace(requirement_id)

    sr_match = SR_ID_PATTERN.fullmatch(requirement_id)

    if sr_match:
        fr = int(sr_match.group(1))
        sr_number = int(sr_match.group(2))

        result.update(
            {
                "valid": True,
                "type": "SR",
                "fr": fr,
                "sr_number": sr_number,
                "parent_sr": f"SR {fr}.{sr_number}",
            }
        )

        return result

    re_match = RE_ID_PATTERN.fullmatch(requirement_id)

    if re_match:
        fr = int(re_match.group(1))
        sr_number = int(re_match.group(2))
        re_number = int(re_match.group(3))

        result.update(
            {
                "valid": True,
                "type": "RE",
                "fr": fr,
                "sr_number": sr_number,
                "re_number": re_number,
                "parent_sr": f"SR {fr}.{sr_number}",
            }
        )

        return result

    return result


