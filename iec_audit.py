# =============================================================================

def write_report(
    audit_data: dict[str, Any],
    path: Path,
) -> None:
    """
    Writes a human-readable audit report.
    """

    summary = audit_data["dataset_summary"]

    lines = []

    lines.append("=" * 78)
    lines.append("IEC 62443-3-3 DATASET AUDIT REPORT")
    lines.append("=" * 78)

    lines.append("")
    lines.append(
        f"Generated at: "
        f"{audit_data['metadata']['audit_generated_at']}"
    )

    lines.append(
        f"Clean dataset: "
        f"{audit_data['metadata']['clean_dataset']}"
    )

    lines.append(
        f"Debug dataset: "
        f"{audit_data['metadata']['debug_dataset']}"
    )

    lines.append("")

    # -------------------------------------------------------------------------
    # Summary
    # -------------------------------------------------------------------------

    lines.append("-" * 78)
    lines.append("DATASET SUMMARY")
    lines.append("-" * 78)

    lines.append(
        f"Total entries : {summary['total_entries']}"
    )

    lines.append(
        f"SRs           : {summary['sr_count']}"
    )

    lines.append(
        f"REs           : {summary['re_count']}"
    )

    lines.append(
        f"Structural pass: "
        f"{'YES' if summary['structural_pass'] else 'NO'}"
    )

    lines.append("")

    lines.append("Entry status:")

    for status in [
        "approved",
        "warning",
        "review",
        "fail",
    ]:
        count = summary["status_counts"].get(status, 0)

        lines.append(
            f"  {status:10s}: {count}"
        )

    lines.append("")

    # -------------------------------------------------------------------------
    # SR coverage
    # -------------------------------------------------------------------------

    coverage = audit_data["sr_coverage"]

    lines.append("-" * 78)
    lines.append("SR COVERAGE")
    lines.append("-" * 78)

    if not coverage["missing_ids"]:
        lines.append(
            "All expected 51 SR IDs are present."
        )
    else:
        lines.append(
            f"Missing SR IDs ({len(coverage['missing_ids'])}):"
        )

        for requirement_id in coverage["missing_ids"]:
            lines.append(f"  - {requirement_id}")

    if coverage["unexpected_ids"]:

        lines.append("")
        lines.append(
            f"Unexpected SR IDs "
            f"({len(coverage['unexpected_ids'])}):"
        )

        for requirement_id in coverage["unexpected_ids"]:
            lines.append(f"  - {requirement_id}")

    lines.append("")

    # -------------------------------------------------------------------------
    # FR distribution
    # -------------------------------------------------------------------------

    lines.append("-" * 78)
    lines.append("FOUNDATIONAL REQUIREMENT DISTRIBUTION")
    lines.append("-" * 78)

    distribution = (
        audit_data[
            "foundational_requirement_distribution"
        ]
    )

    for fr in range(1, 8):

        info = distribution[str(fr)]

        symbol = (
            "OK"
            if info["sr_count_matches_expected"]
            else "WARNING"
        )

        lines.append(
            f"FR {fr}: "
            f"{info['sr_count']} SRs "
            f"(expected {info['expected_sr_count']}), "
            f"{info['re_count']} REs "
            f"[{symbol}]"
        )

    lines.append("")

    # -------------------------------------------------------------------------
    # Duplicate IDs
    # -------------------------------------------------------------------------

    lines.append("-" * 78)
    lines.append("DUPLICATE IDS")
    lines.append("-" * 78)

    duplicate_ids = audit_data["duplicate_ids"]

    if not duplicate_ids:
        lines.append("No duplicate IDs detected.")
    else:
        for requirement_id, count in duplicate_ids.items():
            lines.append(
                f"{requirement_id}: {count} occurrences"
            )

    lines.append("")

    # -------------------------------------------------------------------------
    # Debug coverage
    # -------------------------------------------------------------------------

    lines.append("-" * 78)
    lines.append("DEBUG COVERAGE")
    lines.append("-" * 78)

    debug_coverage = audit_data["debug_coverage"]

    missing_blocks = (
        debug_coverage["missing_from_debug_blocks"]
    )

    missing_consolidation = (
        debug_coverage[
            "missing_from_debug_consolidation"
        ]
    )

    lines.append(
        f"Missing from debug blocks: "
        f"{len(missing_blocks)}"
    )

    for requirement_id in missing_blocks:
        lines.append(f"  - {requirement_id}")

    lines.append(
        f"Missing from debug consolidation: "
        f"{len(missing_consolidation)}"
    )

    for requirement_id in missing_consolidation:
        lines.append(f"  - {requirement_id}")

    lines.append("")

    # -------------------------------------------------------------------------
    # Duplicate text
    # -------------------------------------------------------------------------

    lines.append("-" * 78)
    lines.append("EXACT DUPLICATE TEXT GROUPS")
    lines.append("-" * 78)

    duplicate_texts = audit_data["duplicate_texts"]

    if not duplicate_texts:
        lines.append("No exact duplicate text groups detected.")

    else:

        for duplicate in duplicate_texts:

            lines.append(
                "IDs: "
                + ", ".join(duplicate["ids"])
            )

            lines.append(
                "Text: "
                + duplicate["text"]
            )

            lines.append("")

    lines.append("")

    # -------------------------------------------------------------------------
    # Entries requiring attention
    # -------------------------------------------------------------------------

    lines.append("=" * 78)
    lines.append("ENTRIES REQUIRING ATTENTION")
    lines.append("=" * 78)

    attention_entries = [
        entry
        for entry in audit_data["entries"]
        if entry["status"] != "approved"
    ]

    if not attention_entries:

        lines.append(
            "No entries require attention."
        )

    else:

        for entry in attention_entries:

            lines.append("")
            lines.append("-" * 78)

            lines.append(
                f"{entry['id']} | "
                f"{entry['type']} | "
                f"STATUS: {entry['status'].upper()}"
            )

            lines.append(
                f"Score: "
                f"{entry['score']}/{entry['max_score']}"
            )

            lines.append(
                f"Title: {entry['title']}"
            )

            lines.append(
                f"Words: {entry['word_count']}"
            )

            if entry["issues"]:

                lines.append("Issues:")

                for issue in entry["issues"]:
                    lines.append(f"  - {issue}")

            if entry["warnings"]:

                lines.append("Warnings:")

                for warning in entry["warnings"]:
                    lines.append(f"  - {warning}")

            debug_audit = (
                entry["debug_candidate_audit"]
            )

            lines.append(
                f"Debug occurrences: "
                f"{debug_audit['candidate_occurrences']}"
            )

            lines.append(
                f"Unique text variants: "
                f"{debug_audit['unique_text_variants']}"
            )

            lines.append(
                f"Minimum similarity to final: "
                f"{debug_audit['min_text_similarity_to_final']}"
            )

            if debug_audit["text_variants"]:

                lines.append("")
                lines.append(
                    "Debug text variants:"
                )

                for variant in (
                    debug_audit["text_variants"]
                ):

                    lines.append(
                        f"  Blocks: {variant['blocks']}"
                    )

                    lines.append(
                        f"  Text: {variant['text']}"
                    )

                    lines.append("")

    lines.append("")
    lines.append("=" * 78)
    lines.append("END OF AUDIT REPORT")
    lines.append("=" * 78)

    with path.open("w", encoding="utf-8") as file:
        file.write("\n".join(lines))


