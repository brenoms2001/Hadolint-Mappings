# =============================================================================
# REGULAR EXPRESSIONS
# =============================================================================

SR_ID_PATTERN = re.compile(
    r"^SR\s+([1-7])\.(\d+)$",
    re.IGNORECASE,
)

RE_ID_PATTERN = re.compile(
    r"^SR\s+([1-7])\.(\d+)\s+RE\s+(\d+)$",
    re.IGNORECASE,
)

ANY_ID_PATTERN = re.compile(
    r"^SR\s+[1-7]\.\d+(?:\s+RE\s+\d+)?$",
    re.IGNORECASE,
)


# =============================================================================
# TEXT CONTAMINATION MARKERS
# =============================================================================

# These markers indicate that explanatory or structural PDF content may have
# leaked into the normative requirement text.
CONTAMINATION_PATTERNS = {
    "rationale_and_guidance": re.compile(
        r"\bRationale\s+and\s+supplemental\s+guidance\b",
        re.IGNORECASE,
    ),

    "requirement_enhancements": re.compile(
        r"\bRequirement\s+enhancements?\b",
        re.IGNORECASE,
    ),

    "security_levels": re.compile(
        r"\bSecurity\s+levels?\b",
        re.IGNORECASE,
    ),

    "copyright_notice": re.compile(
        r"\bCopyright\b",
        re.IGNORECASE,
    ),

    "not_for_resale": re.compile(
        r"\bNot\s+for\s+Resale\b",
        re.IGNORECASE,
    ),

    "provided_by": re.compile(
        r"\bProvided\s+by\b",
        re.IGNORECASE,
    ),

    "licensee": re.compile(
        r"\bLicensee\s*=",
        re.IGNORECASE,
    ),

    "void_artifact": re.compile(
        r"\bVoid\b",
        re.IGNORECASE,
    ),

    "pdf_artifact": re.compile(
        r"--[`',\s\-]{5,}",
        re.IGNORECASE,
    ),
}


# =============================================================================
# NORMALIZATION
# =============================================================================

def normalize_whitespace(text: str) -> str:
    """
    Normalizes whitespace without changing semantic content.
    """
    if not isinstance(text, str):
        return ""

    return re.sub(r"\s+", " ", text).strip()


def normalize_for_comparison(text: str) -> str:
    """
    Produces a conservative normalized representation for comparisons.

    We intentionally do not perform aggressive linguistic normalization,
    stemming, or semantic rewriting because the audit must remain
    deterministic and reproducible.
    """
    text = normalize_whitespace(text).lower()

    # Normalize typographic apostrophes/quotes.
    text = (
        text.replace("’", "'")
        .replace("‘", "'")
        .replace("“", '"')
        .replace("”", '"')
    )

    return text


def text_similarity(a: str, b: str) -> float:
    """
    Sequence similarity in [0, 1].
    """
    a_norm = normalize_for_comparison(a)
    b_norm = normalize_for_comparison(b)

    if not a_norm and not b_norm:
        return 1.0

    if not a_norm or not b_norm:
        return 0.0

    return SequenceMatcher(
        None,
        a_norm,
        b_norm,
    ).ratio()


def is_prefix_variant(a: str, b: str) -> bool:
    """
    Returns True if one normalized string is a prefix of the other.

    This is useful for identifying block-boundary variants where one
    extraction captured a complete requirement and another captured a
    shorter version of the same text.
    """
    a_norm = normalize_for_comparison(a)
    b_norm = normalize_for_comparison(b)

    return (
        a_norm.startswith(b_norm)
        or b_norm.startswith(a_norm)
    )


